/**
 * SHRAMIKSETU ATTENDANCE SERVICE v2
 *
 * Replaces typed-UUID attendance with:
 * 1. Rotating QR + HMAC-signed tokens (30s TTL, single-use per worker per day)
 * 2. 6-digit manual code fallback (not a UUID)
 * 3. Server verification: signature, expiry, nonce, active contract, Haversine ≤ 100m,
 *    GPS accuracy threshold, one punch-in/out per day
 * 4. Anti-fraud: mock-location, impossible travel, device sharing → flags, not rejects
 * 5. Offline: accepts punch if token was valid at captured_at timestamp
 */

