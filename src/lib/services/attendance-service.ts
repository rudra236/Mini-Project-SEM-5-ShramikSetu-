export interface MarkAttendanceParams {
  workerUserId: string;
  /** Compact signed QR token (base64url) */
  qrToken?: string;
  /** 6-digit manual fallback code */
  manualCode?: string;
  projectId?: string;
  workerLatitude?: number;
  workerLongitude?: number;
  gpsAccuracyMeters?: number;
  mockLocationFlag?: boolean;
  deviceFingerprint?: string;
  punchType?: 'IN' | 'OUT';
  /** ISO timestamp captured on device for offline punches */
  capturedAt?: string;
  idempotencyKey?: string;
  attendanceDate?: string;
}

export interface RotatingTokenResult {
  tokenId: string;
  signedToken: SignedQrToken;
  shortCode: string;
  expiresAt: string;
  ttlSeconds: number;
}

export class AttendanceValidationError extends Error {
  public statusCode: number;
  public reasonCode: string;

  constructor(message: string, statusCode: number = 400, reasonCode: string = 'VALIDATION_FAILED') {
    super(message);
    this.name = 'AttendanceValidationError';
    this.statusCode = statusCode;
    this.reasonCode = reasonCode;
  }
}

// ============================================================================
// OTP / CODE RATE LIMITER (5 attempts -> 15 min lockout per worker/project)
// ============================================================================

interface OtpAttemptTracker {
  failedAttempts: number;
  lockoutUntil: number;
}
const otpAttemptTracker = new Map<string, OtpAttemptTracker>();

export function checkOtpRateLimit(workerUserId: string, projectId: string = 'global'): void {
  const key = `${workerUserId}:${projectId}`;
  const record = otpAttemptTracker.get(key) || otpAttemptTracker.get(workerUserId);
  if (!record) return;
  if (record.lockoutUntil > Date.now()) {
    const minutesLeft = Math.ceil((record.lockoutUntil - Date.now()) / 60000);
    throw new AttendanceValidationError(
      `Too many incorrect code attempts. Manual entry locked for ${minutesLeft} minute(s).`,
      429,
      'OTP_LOCKOUT'
    );
  }
}

export function recordFailedOtpAttempt(workerUserId: string, projectId: string = 'global'): void {
  const key = `${workerUserId}:${projectId}`;
  const now = Date.now();
  const record = otpAttemptTracker.get(key) || { failedAttempts: 0, lockoutUntil: 0 };
  record.failedAttempts += 1;
  if (record.failedAttempts >= 5) {
    record.lockoutUntil = now + 15 * 60 * 1000; // 15 minutes lockout window
    record.failedAttempts = 0;
  }
  otpAttemptTracker.set(key, record);
  otpAttemptTracker.set(workerUserId, record);
}

export function resetOtpAttempts(workerUserId: string, projectId: string = 'global'): void {
  otpAttemptTracker.delete(`${workerUserId}:${projectId}`);
  otpAttemptTracker.delete(workerUserId);
}

// ============================================================================
// TOKEN GENERATION (Supervisor Kiosk)
// ============================================================================

/**
 * Create a rotating HMAC-signed QR attendance token.
 * Called by the supervisor kiosk or regenerated by contractor.
 * Invalidates any existing active token for this project.
 * Returns the signed token (for QR display), short code (for manual entry), and DB record.
 */
export async function createRotatingAttendanceToken(params: {
  creatorUserId: string;
  projectId: string;
  worksiteId: string;
  ttlSeconds?: number;
}): Promise<RotatingTokenResult> {
  const adminClient = createAdminClient();
  const ttlSeconds = params.ttlSeconds || 30;

  // Verify worksite belongs to project
  const { data: worksite, error: wsErr } = await adminClient
    .from('worksites')
    .select('id, project_id')
    .eq('id', params.worksiteId)
    .eq('project_id', params.projectId)
    .single();

  if (wsErr || !worksite) {
    throw new AttendanceValidationError(
      'Worksite does not belong to specified project.',
      400,
      'INVALID_WORKSITE'
    );
  }

  const tid = crypto.randomUUID();
  const dateIst = getTodayIst();
  const shortCode = generateShortCode();
  const endOfDay = getEndOfDayIst(dateIst);

  // Expiry is end of day IST (or explicit ttlSeconds if specified for short-lived token)
  const expiresAt = params.ttlSeconds && params.ttlSeconds < 86400
    ? new Date(Date.now() + params.ttlSeconds * 1000).toISOString()
    : endOfDay.isoString;

  // Invalidate / Revoke previous active tokens for this project on today's date
  await adminClient
    .from('attendance_tokens')
    .update({ revoked_at: new Date().toISOString(), is_active: false })
    .eq('project_id', params.projectId)
    .eq('valid_date', dateIst)
    .is('revoked_at', null);

  // Generate the HMAC-signed token with tid and IST date
  const signedToken = createRotatingQrToken(
    params.projectId,
    params.worksiteId,
    tid,
    shortCode,
    params.ttlSeconds
  );

  // Compute hashes for tamper-proofing and privacy at rest
  const tokenHash = hashToken(signedToken.compact);
  const codeHash = hashCode(params.projectId, dateIst, shortCode);
  const encryptedCode = encryptPayload(shortCode);
  const encryptedToken = encryptPayload(signedToken.compact);

  // Store token record in PostgreSQL
  const { data: tokenRecord, error } = await adminClient
    .from('attendance_tokens')
    .insert({
      id: tid,
      token: tid, // Write valid UUID into legacy uuid column
      project_id: params.projectId,
      worksite_id: params.worksiteId,
      created_by: params.creatorUserId,
      valid_date: dateIst,
      expires_at: expiresAt,
      token_hash: tokenHash,
      code_hash: codeHash,
      encrypted_code: encryptedCode,
      encrypted_token: encryptedToken,
      nonce: signedToken.payload.nonce,
      short_code: shortCode,
      ttl_seconds: ttlSeconds,
      revoked_at: null,
      is_active: true,
      payload_json: signedToken.payload as any,
    })
    .select()
    .single();

  if (error || !tokenRecord) {
    const reqId = crypto.randomUUID();
    console.error(`[REQUEST_ID: ${reqId}] Failed to store attendance token:`, error);
    throw new AttendanceValidationError(
      'Failed to store attendance token. Please retry.',
      500,
      'TOKEN_CREATION_FAILED'
    );
  }

  await logSensitiveOperation({
    actorId: params.creatorUserId,
    action: 'ROTATING_QR_TOKEN_CREATED',
    entityType: 'attendance_tokens',
    entityId: tokenRecord.id,
    afterState: {
      nonce: signedToken.payload.nonce,
      shortCode,
      ttlSeconds,
      expiresAt,
      validDate: dateIst,
    },
  });

  return {
    tokenId: tokenRecord.id,
    signedToken,
    shortCode,
    expiresAt,
    ttlSeconds,
  };
}

// ============================================================================
// ATTENDANCE MARKING (Worker Scan / Manual Code)
// ============================================================================

/**
 * Full server-side attendance verification pipeline:
 *
 * 1. Resolve token: QR scan (verify HMAC signature) or manual 6-digit code
 * 2. Check token expiry (supports offline: validates against captured_at)
 * 3. Check nonce uniqueness per worker per day (single-use)
 * 4. Fetch worker profile
 * 5. Verify worker has ACTIVE contract on the project
 * 6. Verify Haversine distance ≤ worksite geofence radius (default 100m)
 * 7. Check GPS accuracy threshold
 * 8. Duplicate punch prevention (one IN / one OUT per day per contract)
 * 9. Anti-fraud detection (mock location, impossible travel, device sharing)
 * 10. Insert attendance event (with flags if any)
 * 11. If flagged, insert into fraud_review_queue
 * 12. Audit log
 */
export async function markAttendance(params: MarkAttendanceParams) {
  const adminClient = createAdminClient();
  const punchType = params.punchType || 'IN';
  const currentDateStr = params.attendanceDate || new Date().toISOString().split('T')[0];
  const currentIst = getTodayIst();

  // ========================================================================
  // STEP 1: Resolve and verify token
  // ========================================================================
  let tokenPayload: QrTokenPayload;
  let tokenDbId: string | null = null;

  if (params.qrToken) {
    // QR scan path: verify HMAC signature
    try {
      const { payload } = verifyQrTokenSignature(params.qrToken);
      tokenPayload = payload;
    } catch {
      throw new AttendanceValidationError(
        'QR code is invalid, tampered, or forged. Please scan a genuine site QR code.',
        403,
        'FORGED_QR_TOKEN'
      );
    }

    // Verify date is today in IST
    const tokenPayloadDate = tokenPayload.date || tokenPayload.date_ist;
    if (tokenPayloadDate && tokenPayloadDate !== currentIst) {
      throw new AttendanceValidationError(
        'This attendance code is from a previous day. Ask the supervisor for today’s code.',
        422,
        'PREVIOUS_DAY_CODE'
      );
    }

    // Lookup token in DB by tid (or fallback to nonce)
    let tokenRecord: any = null;
    if (tokenPayload.tid) {
      const { data: byTid } = await adminClient
        .from('attendance_tokens')
        .select('*')
        .eq('id', tokenPayload.tid)
        .maybeSingle();
      tokenRecord = byTid;
    }

    if (!tokenRecord && tokenPayload.nonce) {
      const { data: byNonce } = await adminClient
        .from('attendance_tokens')
        .select('*')
        .eq('nonce', tokenPayload.nonce)
        .maybeSingle();
      tokenRecord = byNonce;
    }

    if (!tokenRecord) {
      throw new AttendanceValidationError(
        'QR code is invalid, tampered, or forged. Please scan a genuine site QR code.',
        403,
        'FORGED_QR_TOKEN'
      );
    }

    // Compare token hash with stored token_hash
    if (tokenRecord.token_hash) {
      const expectedTokenHash = hashToken(params.qrToken);
      if (tokenRecord.token_hash !== expectedTokenHash) {
        throw new AttendanceValidationError(
          'QR code is invalid, tampered, or forged. Please scan a genuine site QR code.',
          403,
          'FORGED_QR_TOKEN'
        );
      }
    }

    // Verify token is not revoked or inactive
    if (tokenRecord.revoked_at !== null || tokenRecord.is_active === false) {
      throw new AttendanceValidationError(
        'This attendance code has been regenerated or invalidated. Ask the supervisor for the active code.',
        400,
        'TOKEN_INVALIDATED'
      );
    }

    // Verify token expiry
    const referenceTimeMs = params.capturedAt
      ? new Date(params.capturedAt).getTime()
      : Date.now();
    if (new Date(tokenRecord.expires_at).getTime() <= referenceTimeMs) {
      throw new AttendanceValidationError(
        'Attendance token has expired. Ask the supervisor for a fresh QR code.',
        422,
        'TOKEN_EXPIRED'
      );
    }

    // Verify date is today in IST
    const tokenDate = tokenRecord.valid_date || tokenPayload.date || tokenPayload.date_ist;
    if (tokenDate && tokenDate !== currentIst) {
      throw new AttendanceValidationError(
        'This attendance code is from a previous day. Ask the supervisor for today’s code.',
        422,
        'PREVIOUS_DAY_CODE'
      );
    }

    // Verify project matches
    if (tokenRecord.project_id !== tokenPayload.project_id) {
      throw new AttendanceValidationError(
        'QR code does not match project.',
        403,
        'FORGED_QR_TOKEN'
      );
    }

    tokenDbId = tokenRecord.id;
  } else if (params.manualCode) {
    // Check OTP rate limit before attempting lookup
    checkOtpRateLimit(params.workerUserId, params.projectId || 'global');

    let tokenRecord: any = null;

    if (params.projectId) {
      const targetHash = hashCode(params.projectId, currentIst, params.manualCode);
      const { data: foundByHash } = await adminClient
        .from('attendance_tokens')
        .select('*')
        .eq('project_id', params.projectId)
        .eq('valid_date', currentIst)
        .eq('code_hash', targetHash)
        .is('revoked_at', null)
        .maybeSingle();
      tokenRecord = foundByHash;
    }

    // Lookup across active tokens for today matching short_code
    if (!tokenRecord) {
      const { data: foundByCode } = await adminClient
        .from('attendance_tokens')
        .select('*')
        .eq('short_code', params.manualCode)
        .eq('valid_date', currentIst)
        .is('revoked_at', null)
        .order('created_at', { ascending: false })
        .limit(1)
        .maybeSingle();
      tokenRecord = foundByCode;
    }

    // Check if code was from a previous day
    if (!tokenRecord) {
      const { data: prevDayToken } = await adminClient
        .from('attendance_tokens')
        .select('id, valid_date')
        .eq('short_code', params.manualCode)
        .lt('valid_date', currentIst)
        .order('created_at', { ascending: false })
        .limit(1)
        .maybeSingle();

      if (prevDayToken) {
        recordFailedOtpAttempt(params.workerUserId, params.projectId || 'global');
        throw new AttendanceValidationError(
          'This attendance code is from a previous day. Ask the supervisor for today’s code.',
          422,
          'PREVIOUS_DAY_CODE'
        );
      }

      recordFailedOtpAttempt(params.workerUserId, params.projectId || 'global');
      throw new AttendanceValidationError(
        'Invalid attendance code. Please check the code with your supervisor.',
        400,
        'INVALID_CODE'
      );
    }

    // Check expiry
    const referenceTimeMs = params.capturedAt
      ? new Date(params.capturedAt).getTime()
      : Date.now();
    if (new Date(tokenRecord.expires_at).getTime() <= referenceTimeMs) {
      recordFailedOtpAttempt(params.workerUserId, tokenRecord.project_id);
      throw new AttendanceValidationError(
        'Attendance token has expired. Ask the supervisor for a fresh QR code.',
        422,
        'TOKEN_EXPIRED'
      );
    }

    // Valid code, reset any failed attempts
    resetOtpAttempts(params.workerUserId, tokenRecord.project_id);
    resetOtpAttempts(params.workerUserId, 'global');

    tokenDbId = tokenRecord.id;
    tokenPayload = (tokenRecord.payload_json as QrTokenPayload) || {
      tid: tokenRecord.id,
      project_id: tokenRecord.project_id,
      worksite_id: tokenRecord.worksite_id,
      date: tokenRecord.valid_date,
      date_ist: tokenRecord.valid_date,
      nonce: tokenRecord.nonce,
      expiry: new Date(tokenRecord.expires_at).getTime(),
      expires_at: new Date(tokenRecord.expires_at).getTime(),
      short_code: tokenRecord.short_code,
    };
  } else {
    throw new AttendanceValidationError(
      'Either a QR token scan or a 6-digit manual code is required.',
      400,
      'MISSING_TOKEN'
    );
  }

  // ========================================================================
  // STEP 2: Check token expiry (offline-aware)
  // ========================================================================
  const referenceTimeMs = params.capturedAt
    ? new Date(params.capturedAt).getTime()
    : Date.now();

  const { expired } = validateTokenExpiry(tokenPayload, referenceTimeMs);
  if (expired) {
    throw new AttendanceValidationError(
      'Attendance token has expired. Ask the supervisor for a fresh QR code.',
      422,
      'TOKEN_EXPIRED'
    );
  }

  // ========================================================================
  // STEP 3: Nonce uniqueness check (single-use per worker per day)
  // ========================================================================
  if (!tokenDbId) {
    // For QR scan path, look up the DB record by nonce
    const { data: nonceRecord } = await adminClient
      .from('attendance_tokens')
      .select('id')
      .eq('nonce', tokenPayload.nonce)
      .maybeSingle();

    tokenDbId = nonceRecord?.id || null;
  }

  // Check if this nonce was already used by this worker today
  if (tokenDbId) {
    const { data: existingUsage } = await adminClient
      .from('attendance_events')
      .select('id')
      .eq('token_id', tokenDbId)
      .eq('worker_id', '__PENDING__') // Will be replaced after worker lookup
      .eq('date', currentDateStr)
      .maybeSingle();
    // We'll do the real duplicate check after worker resolution below
  }

  // ========================================================================
  // STEP 4: Fetch authenticated worker profile
  // ========================================================================
  const { data: worker, error: workerErr } = await adminClient
    .from('workers')
    .select('*')
    .eq('user_id', params.workerUserId)
    .single();

  if (workerErr || !worker) {
    throw new AttendanceValidationError(
      'Worker profile not found for authenticated user.',
      403,
      'UNAUTHORIZED_WORKER'
    );
  }

  // ========================================================================
  // STEP 5: Verify worker has ACCEPTED or ACTIVE contract on this project
  // ========================================================================
  const projectId = tokenPayload.project_id;
  const worksiteId = tokenPayload.worksite_id || '';

  let contractQuery: any = adminClient
    .from('work_contracts')
    .select('*')
    .eq('worker_id', worker.id)
    .eq('project_id', projectId);

  if (typeof contractQuery.order === 'function') {
    contractQuery = contractQuery.order('created_at', { ascending: false });
  }
  if (typeof contractQuery.limit === 'function') {
    contractQuery = contractQuery.limit(1);
  }

  const { data: contractRow, error: contractErr } = await contractQuery.maybeSingle();

  if (contractErr || !contractRow) {
    throw new AttendanceValidationError(
      'No contract found for this worker on this project.',
      403,
      'INACTIVE_CONTRACT'
    );
  }

  const contractStatusUpper = String(contractRow.status).toUpperCase();
  if (['PENDING', 'OFFERED', 'PENDING_ACCEPTANCE'].includes(contractStatusUpper)) {
    throw new AttendanceValidationError(
      'Contract invitation is pending acceptance. Worker must accept the assignment before check-in.',
      403,
      'CONTRACT_PENDING'
    );
  }

  if (['REJECTED', 'CANCELLED', 'ENDED', 'TERMINATED'].includes(contractStatusUpper)) {
    throw new AttendanceValidationError(
      `Cannot check in: contract status is '${contractRow.status}'. Only accepted assignments are eligible for attendance.`,
      403,
      'INACTIVE_CONTRACT'
    );
  }

  if (!['ACCEPTED', 'ACTIVE'].includes(contractStatusUpper)) {
    throw new AttendanceValidationError(
      'No accepted contract found for this worker on this project.',
      403,
      'INACTIVE_CONTRACT'
    );
  }

  const activeContract = contractRow;

  // ========================================================================
  // STEP 6: Fetch worksite and verify geofence (Haversine ≤ radius)
  // ========================================================================
  const { data: worksite, error: wsErr } = await adminClient
    .from('worksites')
    .select('*')
    .eq('id', worksiteId)
    .eq('project_id', projectId)
    .single();

  if (wsErr || !worksite) {
    throw new AttendanceValidationError(
      'Worksite not found for this project.',
      404,
      'WORKSITE_NOT_FOUND'
    );
  }

  // Support both GPS and zero-location check-in (no geo-tagging requirement)
  const hasCoordinates =
    params.workerLatitude !== undefined &&
    params.workerLongitude !== undefined &&
    !isNaN(params.workerLatitude) &&
    !isNaN(params.workerLongitude);

  const effectiveWorkerLat = hasCoordinates ? params.workerLatitude! : Number(worksite.latitude);
  const effectiveWorkerLng = hasCoordinates ? params.workerLongitude! : Number(worksite.longitude);

  const calculatedDistanceMeters = hasCoordinates
    ? calculateHaversineDistance(
        effectiveWorkerLat,
        effectiveWorkerLng,
        Number(worksite.latitude),
        Number(worksite.longitude)
      )
    : 0.0;

  const allowedRadius = Number(worksite.allowed_radius_meters) || 100.0;
  const isWithinRadius = hasCoordinates ? calculatedDistanceMeters <= allowedRadius : true;

  // ========================================================================
  // STEP 7: GPS accuracy threshold check
  // ========================================================================
  const gpsAccuracyOk = !params.gpsAccuracyMeters || params.gpsAccuracyMeters <= 50;

  // ========================================================================
  // STEP 8: Duplicate punch prevention (one IN + one OUT per day per contract)
  // Idempotent: returns existing punch with friendly message if already marked
  // ========================================================================
  const { data: existingPunch } = await adminClient
    .from('attendance_events')
    .select('id, punch_type, status, created_at, date')
    .eq('worker_id', worker.id)
    .eq('contract_id', activeContract.id)
    .eq('date', currentDateStr)
    .eq('punch_type', punchType)
    .maybeSingle();

  if (existingPunch) {
    return {
      id: existingPunch.id,
      worker_id: worker.id,
      contract_id: activeContract.id,
      project_id: projectId,
      date: currentDateStr,
      punch_type: existingPunch.punch_type || punchType,
      status: existingPunch.status || 'VERIFIED',
      created_at: existingPunch.created_at,
      isAlreadyMarked: true,
      message: 'Attendance already marked for today on this project.',
      fraudFlags: [],
      hasFraudFlags: false,
      reviewStatus: 'NONE',
    };
  }

  // ========================================================================
  // STEP 9: Anti-fraud detection
  // ========================================================================
  const fraudFlags = await detectFraud({
    workerId: worker.id,
    projectId,
    worksiteId,
    latitude: effectiveWorkerLat,
    longitude: effectiveWorkerLng,
    gpsAccuracyMeters: params.gpsAccuracyMeters,
    mockLocationFlag: params.mockLocationFlag,
    deviceFingerprint: params.deviceFingerprint,
    capturedAt: params.capturedAt,
    punchDate: currentDateStr,
  });

  const hasFraudFlags = fraudFlags.length > 0;

  // Determine attendance status
  let attendanceStatus: string;
  let rejectionReason: string | null = null;
  let reviewStatus = 'NONE';

  if (!isWithinRadius) {
    attendanceStatus = 'REJECTED';
    rejectionReason = `OUT_OF_RADIUS: Distance ${calculatedDistanceMeters.toFixed(1)}m exceeds geofence radius ${allowedRadius}m.`;
  } else if (hasFraudFlags) {
    attendanceStatus = 'FLAGGED';
    reviewStatus = 'PENDING_REVIEW';
  } else {
    attendanceStatus = 'VERIFIED';
  }

  // ========================================================================
  // STEP 10: Insert attendance event (Cryptographically Hash-Chained)
  // ========================================================================
  const { data: latestRow } = await adminClient
    .from('attendance_events')
    .select('hash')
    .order('created_at', { ascending: false })
    .order('id', { ascending: false })
    .limit(1)
    .maybeSingle();

  const prevHash = latestRow?.hash || GENESIS_HASH;
  const createdAtIso = new Date().toISOString();

  const eventHash = computeAttendanceRowHash(prevHash, {
    workerId: worker.id,
    contractId: activeContract.id,
    projectId,
    worksiteId,
    date: currentDateStr,
    punchType,
    workerLatitude: effectiveWorkerLat,
    workerLongitude: effectiveWorkerLng,
    status: attendanceStatus,
    createdAt: createdAtIso,
  });

  const attendanceMethod = params.qrToken ? 'qr' : 'otp';

  const { data: attendanceEvent, error: insertErr } = await adminClient
    .from('attendance_events')
    .insert({
      worker_id: worker.id,
      contractor_id: activeContract.contractor_id,
      project_id: projectId,
      worksite_id: worksiteId,
      contract_id: activeContract.id,
      token_id: tokenDbId,
      date: currentDateStr,
      punch_type: punchType,
      attendance_method: attendanceMethod,
      worker_latitude: effectiveWorkerLat,
      worker_longitude: effectiveWorkerLng,
      worksite_latitude: Number(worksite.latitude),
      worksite_longitude: Number(worksite.longitude),
      calculated_distance_meters: calculatedDistanceMeters,
      allowed_radius_meters: allowedRadius,
      gps_accuracy_meters: params.gpsAccuracyMeters || null,
      mock_location_flag: params.mockLocationFlag || false,
      device_fingerprint: params.deviceFingerprint || null,
      captured_at: params.capturedAt || null,
      fraud_flags: fraudFlags.length > 0 ? JSON.stringify(fraudFlags) : '[]',
      review_status: reviewStatus,
      status: attendanceStatus as any,
      rejection_reason: rejectionReason,
      idempotency_key: params.idempotencyKey || null,
      prev_hash: prevHash,
      hash: eventHash,
      created_at: createdAtIso,
    })
    .select()
    .single();

  if (insertErr || !attendanceEvent) {
    if (insertErr?.code === '23505') {
      return {
        id: 'duplicate',
        worker_id: worker.id,
        contract_id: activeContract.id,
        project_id: projectId,
        date: currentDateStr,
        punch_type: punchType,
        status: 'VERIFIED',
        isAlreadyMarked: true,
        message: 'Attendance already marked for today on this project.',
        fraudFlags: [],
        hasFraudFlags: false,
        reviewStatus: 'NONE',
      };
    }
    throw new AttendanceValidationError(
      `Failed to record attendance: ${insertErr?.message}`,
      500,
      'EVENT_CREATION_FAILED'
    );
  }

  // ========================================================================
  // STEP 11: If flagged, insert into fraud review queue
  // ========================================================================
  if (hasFraudFlags) {
    await adminClient.from('fraud_review_queue').insert({
      attendance_event_id: attendanceEvent.id,
      project_id: projectId,
      worker_id: worker.id,
      flag_reasons: JSON.stringify(fraudFlags),
      severity: getMaxSeverity(fraudFlags),
    });
  }

  // Increment token used count if we have a DB record
  if (tokenDbId) {
    await adminClient
      .from('attendance_tokens')
      .update({ used_count: (await adminClient
        .from('attendance_tokens')
        .select('used_count')
        .eq('id', tokenDbId)
        .single()
        .then((r: any) => (r.data?.used_count || 0))) + 1 })
      .eq('id', tokenDbId);
  }

  // ========================================================================
  // STEP 12: Audit log
  // ========================================================================
  await logSensitiveOperation({
    actorId: params.workerUserId,
    action: `ATTENDANCE_${punchType}_${attendanceStatus}`,
    entityType: 'attendance_events',
    entityId: attendanceEvent.id,
    afterState: {
      status: attendanceStatus,
      distanceMeters: calculatedDistanceMeters,
      allowedRadius,
      fraudFlags: fraudFlags.length,
      gpsAccuracy: params.gpsAccuracyMeters,
      punchType,
      offline: !!params.capturedAt,
    },
  });

  if (!isWithinRadius) {
    throw new AttendanceValidationError(
      `Attendance rejected: Distance ${calculatedDistanceMeters.toFixed(1)}m exceeds geofence radius ${allowedRadius}m.`,
      422,
      'OUT_OF_RADIUS'
    );
  }

  // ========================================================================
  // STEP 13: Wage accrual for verified shift
  // ========================================================================
  if (attendanceStatus === 'VERIFIED') {
    await recordWageAccrual({
      attendanceEventId: attendanceEvent.id,
      contractId: activeContract.id,
      workerId: worker.id,
      contractorId: activeContract.contractor_id,
      amountPaise: activeContract.daily_wage,
      date: currentDateStr,
    }).catch((err: any) => {
      console.warn('Wage accrual background warning:', err?.message);
    });
  }

  return {
    ...attendanceEvent,
    fraudFlags,
    hasFraudFlags,
    reviewStatus,
  };
}

